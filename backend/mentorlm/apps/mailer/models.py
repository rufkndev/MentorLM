"""Журнал отправленных писем — след того, что мы действительно отправили.

Существует по двум причинам, и первая из них юридическая. Оферта (п. 7.3) и
ФЗ-376 требуют уведомить о списании за 24 часа, а при отсутствии уведомления
платёж подлежит полному возврату (п. 7.6). До появления этой таблицы
доказательством был `Subscription.renewal_notified_at` — то есть запись «мы
решили отправить», а не «отправили»: `mailer.sender` работает в демон-потоке и
глушит любую ошибку SMTP, поэтому недоставленное письмо не оставляло следа
нигде. Теперь у каждой попытки есть строка с ответом транспорта.

Вторая причина бытовая: «письмо не пришло» — обращение, на которое без журнала
нечего ответить. Здесь видно, была ли попытка, на какой адрес и что сказал SMTP.

Пользователь не ссылкой, а снимком адреса — как в `billing.Payment.user_email`:
запись обязана оставаться читаемой после удаления аккаунта (иначе доказательство
уведомления исчезает вместе с ним), и письма уходят на адреса, за которыми
аккаунта может не быть вовсе.

Строк мало по природе — несколько на пользователя за всю его жизнь, — поэтому
ретеншена у таблицы нет: она дешевле любого правила чистки.
"""

from django.db import models


class SentLetter(models.Model):
    """Одна попытка отправки письма и её исход."""

    class Status(models.TextChoices):
        SENT = "sent", "Отправлено"
        FAILED = "failed", "Ошибка"

    to_email = models.EmailField(db_index=True)
    # Ключ из mailer.letters.LETTERS. Строка, а не choices: каталог писем
    # меняется, а журнал остаётся — исторические имена должны читаться и после
    # того, как письмо из каталога убрали.
    letter = models.CharField(max_length=50, db_index=True)
    # Снимок темы: каталог правят, а предъявлять придётся то, что человек
    # получил, а не то, что написано в коде сегодня.
    subject = models.CharField(max_length=255, blank=True)
    status = models.CharField(max_length=10, choices=Status.choices)
    # Текст исключения от транспорта — единственное, что объясняет отказ.
    error = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "Отправленное письмо"
        verbose_name_plural = "Отправленные письма"
        ordering = ("-created_at",)
        indexes = [
            # «что уходило на этот адрес» и «что не отправилось за сутки» —
            # два единственных запроса, с которыми сюда приходят.
            models.Index(fields=["to_email", "-created_at"]),
            models.Index(fields=["status", "-created_at"]),
        ]

    def __str__(self) -> str:
        return f"{self.letter} → {self.to_email} ({self.get_status_display()})"
