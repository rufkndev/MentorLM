@dataclass(frozen=True)
class ModeQuota:
    """Квота режима в µ$ на каждое окно; None — безлимит, 0 — режим недоступен."""

    burst: int | None
    week: int | None

    def limit(self, window: str) -> int | None:
        """Лимит по ключу окна из QUOTA_WINDOWS."""
        return getattr(self, window)


# $1 = 1_000_000 µ$ — множитель перевода авторских долларов в единицу расхода.
_MICRO = 1_000_000

# Доли режимов в месячном бюджете тарифа (сумма = 1). Общие для всех тарифов:
# расхождение долей по тарифам сделало бы «сколько ответов даёт тариф»
# непредсказуемым для каждого режима отдельно.
_MODE_SHARES = {"chat": 5 / 12, "code": 4 / 12, "research": 3 / 12}

# Доля недельной квоты, доступная в одном 5ч-окне. Время-пропорционально было бы
# 5/168 ≈ 0.03 — это запрет всплесков и ~1 ответ за 5 часов; 25% пропускают
# нормальную учебную сессию, не трогая недельный потолок.
BURST_SHARE_OF_WEEK = 0.25

# Недель в среднем месяце (30.44 / 7). Делить на 4 значит разрешить на 9%
# больше, чем написано в потолке тарифа: окна скользящие и про календарь не
# знают, поэтому за месяц в недельную квоту укладывается 4.35 окна, а не 4.
WEEKS_PER_MONTH = 4.348


def _plan_quotas(
    budget_usd: float,
    *,
    weeks: float = WEEKS_PER_MONTH,
    burst_share: float = BURST_SHARE_OF_WEEK,
) -> dict[str, ModeQuota]:
    """Раскидать бюджет тарифа по режимам и окнам, вернуть µ$.

    Бюджет → доля режима → неделя = бюджет / `weeks` (главный потолок) → 5ч-окно
    = `burst_share` недели (ограничивает скорость расхода, но разрешает сессию).

    `weeks=1` превращает бюджет в потолок на одно недельное окно целиком — так
    задаётся квота подписки короче недели (триал: 24 ч), где окно не успевает
    истечь и работает общим лимитом. Для месячных тарифов параметр не трогают.
    """
    quotas: dict[str, ModeQuota] = {}
    for mode, share in _MODE_SHARES.items():
        week = round(budget_usd * share / weeks * _MICRO)
        quotas[mode] = ModeQuota(burst=round(week * burst_share), week=week)
    return quotas


