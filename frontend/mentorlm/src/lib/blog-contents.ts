// Все статьи, отсортированные от новых к старым (для листинга /blog).
export const sortedPosts: readonly BlogPost[] = [...posts].sort((a, b) =>
  b.date.localeCompare(a.date)
);

// Находит статью по slug (или undefined). Используется страницей /blog/[slug].
export function getPostBySlug(slug: string): BlogPost | undefined {
  return posts.find((p) => p.slug === slug);
}

// Форматирует ISO-дату в человекочитаемый вид на русском ("23 июля 2026").
export function formatPostDate(iso: string): string {
  return new Date(iso).toLocaleDateString("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}
