"""Пермишены сверх тех, что есть в DRF из коробки.

Пока здесь один — `EmailVerified`. Он существует отдельным классом, а не
проверкой внутри вьюхи, ровно по одной причине: платёжных эндпоинтов ещё нет,
а правило уже есть. Класс, который достаточно дописать в `permission_classes`,
переживёт это ожидание лучше, чем строчка в чьей-то голове.
"""

from rest_framework.exceptions import PermissionDenied
from rest_framework.permissions import BasePermission


class EmailVerified(BasePermission):
    """Требует подтверждённой почты.

    ⚠️ Вешать на всё, что связано с деньгами: оформление подписки, привязку
    карты, изменение платёжных данных. Не вешать на продукт — работать с ИИ
    можно и с неподтверждённой почтой (см. dev_docs/notes/emailNote.md, §5).

    Логика такая: пока человек не платит, потерянный из-за опечатки в адресе
    аккаунт — его личная неприятность. Как только появляются деньги и
    автосписания, тот же потерянный аккаунт становится нашей проблемой: по
    ФЗ-376 мы обязаны предупреждать о списании за 24 часа, а предупреждать
    некуда, если письма уходят в чужой или несуществующий ящик.
    """

    def has_permission(self, request, view) -> bool:
        user = request.user
        if not (user and user.is_authenticated):
            # Не наш случай — пусть отвечает IsAuthenticated.
            return False
        if getattr(user, "email_verified", False):
            return True

        # detail словарём, а не строкой: DRF отдаёт dict как тело ответа как
        # есть, и фронт получает привычный {code, message} вместо {detail}.
        raise PermissionDenied(
            {
                "code": "email_not_verified",
                "message": "Подтвердите почту — на неё придёт чек и "
                "уведомления о списаниях.",
            }
        )
