"""Адрес клиента — одно определение на весь проект.

Единственный способ узнать, с какого адреса реально пришёл запрос, — взять
ПОСЛЕДНИЙ элемент `X-Forwarded-For`. Наш nginx настроен как
`$proxy_add_x_forwarded_for` (infra/nginx/proxy_params.conf): он ДОПИСЫВАЕТ
адрес соединения в конец списка, а всё, что левее, прислал сам клиент.

Отсюда правило: любой левый элемент — это ввод пользователя. Счётчик,
построенный на нём, обходится одной строкой в curl (`-H 'X-Forwarded-For:
1.2.3.4'` с новым числом на каждый запрос даёт бесконечный запас попыток), а
аллоу-лист по нему просто ничего не проверяет.

Функция живёт в core, а не рядом с одним из потребителей, именно чтобы вторая
копия не появилась снова и не разъехалась с первой.
"""

from __future__ import annotations


def client_ip(request) -> str:
    """Адрес клиента, который нельзя подделать заголовком."""
    forwarded = request.META.get("HTTP_X_FORWARDED_FOR", "")
    if forwarded:
        return forwarded.split(",")[-1].strip()
    return request.META.get("REMOTE_ADDR", "")
