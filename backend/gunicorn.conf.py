"""Конфигурация gunicorn для прода — единственное место настройки воркеров.

Всё здесь подчинено потоковым ответам: `apps/conversations/views.py` отдаёт SSE
длиной до 900 секунд (billing.limits.REQUEST_TIMEOUT_SECONDS), и обычный
sync-воркер такой запрос не переживёт.
"""

bind = "0.0.0.0:8000"

# gthread, а не sync: воркер держит пул потоков, и один долгий стрим занимает
# поток, а не весь процесс. Плюс у gthread `timeout` сторожит живость воркера,
# а не длительность запроса — долгие ответы не расстреливаются.
# Асинхронные воркеры не подходят: код синхронный (вьюхи, SDK провайдеров),
# и на ожидании ответа модели GIL всё равно отпускается.
worker_class = "gthread"
workers = 2  # ≈ числу ядер сервера
threads = 16  # workers × threads = потолок одновременных ответов
# ⚠️ Он же — потолок соединений с Postgres при CONN_MAX_AGE > 0 (settings.prod).

# С запасом над самым долгим режимом (900 с), иначе воркер сочтут зависшим.
timeout = 1200
# Сколько ждать завершения активных ответов при перезапуске (деплой).
graceful_timeout = 60
keepalive = 5

# Плановая переработка воркера — страховка от утечек памяти в долгих процессах.
max_requests = 1000
max_requests_jitter = 100

# Heartbeat в память, а не на диск контейнера.
worker_tmp_dir = "/dev/shm"

# Логи в stdout/stderr — их забирает docker (ротация настроена в compose).
accesslog = "-"
errorlog = "-"
loglevel = "info"
