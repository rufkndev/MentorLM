"""Каталог писем — единственное место, где перечислено, что мы вообще шлём.

Одно письмо = одна запись здесь + пара шаблонов `templates/emails/<name>.{html,txt}`.
Тема живёт рядом с шаблоном, а не в вызывающем коде: иначе одно и то же письмо
уходило бы с разными темами из разных мест.

Добавить письмо (например, «пароль изменён» или напоминание о списании за 24
часа по ФЗ-376) = добавить запись сюда и два шаблона. Больше нигде ничего
менять не нужно.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Letter:
    """Описание письма: тема и базовое имя пары шаблонов."""

    subject: str
    # Без расширения: sender добавит .txt и .html.
    template: str


# Ключ — то, что передают в mailer.send: короткое имя письма.
LETTERS: dict[str, Letter] = {
    # Подтверждение адреса при регистрации. Без него пользователь не сможет
    # восстановить пароль, а мы не будем уверены, что почта вообще его.
    "verify_email": Letter(
        subject="Подтвердите почту в MentorLM",
        template="emails/verify_email",
    ),
    # Сброс забытого пароля. Единственный способ вернуть доступ к аккаунту.
    "password_reset": Letter(
        subject="Сброс пароля в MentorLM",
        template="emails/password_reset",
    ),
}
