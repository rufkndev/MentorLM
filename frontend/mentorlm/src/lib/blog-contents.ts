// Блок тела статьи. Порядок в массиве = порядок на странице.
export type BlogBlock =
  | { type: "h2"; text: string } // подзаголовок раздела
  | { type: "h3"; text: string } // подзаголовок ниже уровнем
  | { type: "p"; text: string } // абзац
  | { type: "ul"; items: readonly string[] } // маркированный список
  | { type: "ol"; items: readonly string[] } // нумерованный список
  | { type: "quote"; text: string }; // выделенная цитата

// Одна статья блога.
export type BlogPost = {
  slug: string; // часть URL: /blog/<slug>; латиница-дефис, уникально
  title: string; // заголовок статьи
  excerpt: string; // краткое описание для карточки и SEO
  tag: string; // рубрика (Гайд / Продукт / Кейс …)
  date: string; // дата публикации в ISO: "2026-07-23"
  readingMinutes: number; // примерное время чтения
  content: readonly BlogBlock[]; // тело статьи блоками
};

